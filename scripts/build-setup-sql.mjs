// Concatenates supabase/migrations/*.sql into supabase/setup.sql: one file to paste
// into the Supabase SQL editor for a first install (no CLI needed).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "supabase/migrations";
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const parts = files.map((f) => `-- ===== ${f} =====\n${readFileSync(join(dir, f), "utf8").trim()}\n`);
const header = `-- projets-gestion — full database setup (generated by scripts/build-setup-sql.mjs, do not edit)
-- 1. Replace the email on the last line with the email of the person who will be the first admin.
-- 2. Paste this whole file in Supabase > SQL Editor > New query, then Run. Run it once, on a new project.
-- Later updates: run only the new files from supabase/migrations, in order.
`;
const footer = `
-- ===== first admin =====
-- Only this email can create the workspace on first sign-in. Add more lines for more people.
insert into bootstrap_admins (email) values (lower('CHANGE-ME@example.org'));
`;
writeFileSync("supabase/setup.sql", [header, ...parts, footer].join("\n"));
console.log(`supabase/setup.sql: ${files.length} migrations`);
